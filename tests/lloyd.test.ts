function clean(edges: number[]): number[] {
  const z = edges.indexOf(0);
  return z === -1 ? edges : edges.slice(0, z);
}

describe("Lloyd protocol", () => {
  describe("decode real hardware captures", () => {
    for (const c of CAPTURES) {
      it(c.name, () => {
        const state = decodeLloyd(clean(c.edges));
        expect(state, `${c.name} should decode`).not.toBeNull();
        for (const [k, v] of Object.entries(c.expect)) {
          expect(state![k as keyof LloydState], `${c.name}: ${k}`).toBe(v as never);
        }
      });
    }

    it("decodes via the top-level dispatcher (registry wiring)", () => {
      const r = decode(clean(CAPTURES[0]!.edges), { protocol: "lloyd" });
      expect(r).not.toBeNull();
      expect(r!.protocol).toBe("lloyd");
      expect((r as { state: LloydState }).state.mode).toBe(LloydMode.Cool);
    });
  });

  describe("checksum", () => {
    it("is the one's-complement byte sum of B0..B13", () => {
      const data = buildLloydRaw(defaultLloydState());
      let sum = 0;
      for (let i = 0; i < LLOYD_STATE_LENGTH - 1; i++) sum += data[i]!;
      expect(data[14]).toBe((~sum) & 0xff);
      expect(data[14]).toBe(lloydChecksum(data));
    });

    it("matches the known signature + checksum on a real frame", () => {
      // Cool 25°C Auto → 36 0f e8 80 32 00..00 08 80 00..00 98
      const data = buildLloydRaw({
        ...defaultLloydState(), mode: LloydMode.Cool, fan: LloydFan.Auto, temp: 25,
      });
      expect([...data]).toEqual([0x36, 0x0f, 0xe8, 0x80, 0x32, 0, 0, 0, 0, 0x08, 0x80, 0, 0, 0, 0x98]);
    });
  });

  describe("encode → decode roundtrip", () => {
    const modes = Object.values(LloydMode);
    const fans = Object.values(LloydFan);
    const swings = Object.values(LloydSwingV);

    it("roundtrips across the mapped state space", () => {
      for (const mode of modes) {
        for (const fan of fans) {
          for (const temp of [16, 20, 24, 30]) {
            for (const swingV of swings) {
              const state: LloydState = {
                power: true, mode, fan, temp,
                turbo: false, sleep: false, eco: false,
                swingV, swingH: false, display: true,
              };
              const back = decodeLloyd(sendLloyd(state));
              expect(back, `mode ${mode} fan ${fan} temp ${temp} swingV ${swingV}`).toEqual(state);
            }
          }
        }
      }
    });

    it("roundtrips every boolean toggle independently", () => {
      const base = defaultLloydState();
      for (const key of ["power", "turbo", "sleep", "eco", "swingH", "display"] as const) {
        const state = { ...base, [key]: !base[key] } as LloydState;
        expect(decodeLloyd(sendLloyd(state)), `toggle ${key}`).toEqual(state);
      }
    });

    it("derives the fan-mode flag (B9 bit7) only in Fan mode", () => {
      const fanState = { ...defaultLloydState(), mode: LloydMode.Fan };
      expect(buildLloydRaw(fanState)[9]! & 0x80).toBe(0x80);
      const coolState = { ...defaultLloydState(), mode: LloydMode.Cool };
      expect(buildLloydRaw(coolState)[9]! & 0x80).toBe(0);
    });

    it("clamps temperature to 16–30 °C", () => {
      expect(buildLloydRaw({ ...defaultLloydState(), temp: 5 })[4]).toBe(16 << 1);
      expect(buildLloydRaw({ ...defaultLloydState(), temp: 99 })[4]).toBe(30 << 1);
    });
  });

  describe("rejection", () => {
    it("rejects a bad checksum", () => {
      const data = buildLloydRaw(defaultLloydState());
      data[14] = (data[14]! ^ 0xff) & 0xff;
      expect(parseLloydState(data)).toBeNull();
    });

    it("rejects a wrong signature", () => {
      const data = buildLloydRaw(defaultLloydState());
      data[0] = 0x37;
      data[14] = lloydChecksum(data);
      expect(parseLloydState(data)).toBeNull();
    });

    it("rejects truncated timing input", () => {
      expect(decodeLloyd([1020, 580, 1020, 2540])).toBeNull();
    });

    it("rejects random noise", () => {
      const noise = Array.from({ length: 240 }, (_, i) => (i % 2 ? 400 : 9000));
      expect(decodeLloyd(noise)).toBeNull();
    });
  });
});
